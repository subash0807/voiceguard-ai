// src/screens/ResultScreen.js
import React, { useState } from 'react';
import { View, Text, StyleSheet, ScrollView, TouchableOpacity, Share } from 'react-native';
import { colors, riskColors } from '../utils/theme';
import { CATEGORIES, RECOMMENDATIONS, EMERGENCY_CONTACTS, BANK_HELPLINES } from '../utils/detector';

export default function ResultScreen({ route, navigation }) {
  const { result, transcript, filename, language } = route.params;
  const { score, category, icon, categoryHits, scamType, actionSteps } = result;
  const [tab, setTab] = useState(0);
  const tabs = ['📝 Transcript', '⚠️ Findings', '🛡️ Action Plan', '📞 Helplines'];
  const rc = riskColors[category] || riskColors['Low'];

  const findings = Object.entries(categoryHits).map(([key, hits]) => ({
    key, hits, ...CATEGORIES[key],
    contribution: Math.round(CATEGORIES[key].weight * Math.log1p(hits) * 10 * 10) / 10,
  })).sort((a, b) => b.contribution - a.contribution);

  const recs = findings.map(f => RECOMMENDATIONS[f.key]).filter(Boolean);

  const handleShare = async () => {
    const text = `VoiceGuard AI Report\nFile: ${filename}\nRisk Score: ${score}/100 (${category})\nScam Type: ${scamType?.name || 'Unknown'}\nThreats: ${findings.map(f => f.label).join(', ')}\n\nReport generated by VoiceGuard AI`;
    await Share.share({ message: text });
  };

  const pillColor = (w) => w >= 3 ? '#ff8a80' : w >= 2.5 ? '#ffcc80' : w >= 2 ? '#fff176' : '#69f0ae';
  const pillLabel = (w) => w >= 3 ? 'Critical' : w >= 2.5 ? 'High' : w >= 2 ? 'Medium' : 'Low';

  return (
    <View style={s.root}>
      <ScrollView showsVerticalScrollIndicator={false}>

        {/* Risk banner */}
        <View style={[s.banner, { backgroundColor: rc.bg, borderLeftColor: rc.border }]}>
          <View style={s.bannerRow}>
            <Text style={s.bannerIcon}>{icon}</Text>
            <View style={s.bannerText}>
              <Text style={[s.bannerScore, { color: rc.text }]}>{score}/100</Text>
              <Text style={[s.bannerCat, { color: rc.text }]}>{category} Risk</Text>
            </View>
            <TouchableOpacity style={s.shareBtn} onPress={handleShare}>
              <Text style={s.shareBtnText}>Share</Text>
            </TouchableOpacity>
          </View>
          <Text style={s.disclaimer}>⚠️ Heuristic score — not a validated fraud probability. Verify independently.</Text>
        </View>

        {/* Metrics */}
        <View style={s.metrics}>
          {[
            ['Score', `${score}/100`],
            ['Level', category],
            ['Threats', Object.keys(categoryHits).length],
            ['Lang', language?.toUpperCase() || 'AUTO'],
          ].map(([l, v]) => (
            <View key={l} style={s.metric}>
              <Text style={s.metricVal}>{v}</Text>
              <Text style={s.metricLbl}>{l}</Text>
            </View>
          ))}
        </View>

        {/* Scam type card */}
        {scamType && (
          <View style={s.scamCard}>
            <Text style={s.scamLabel}>IDENTIFIED SCAM TYPE</Text>
            <Text style={s.scamTitle}>{scamType.icon} {scamType.name}</Text>
            <View style={s.scamStat}><Text style={s.scamStatText}>📊 {scamType.stat}</Text></View>
          </View>
        )}

        {/* Score bar */}
        <View style={s.scoreBarWrap}>
          <View style={s.scoreBarBg}>
            <View style={[s.scoreBarFill, {
              width: `${score}%`,
              backgroundColor: score >= 75 ? colors.red : score >= 50 ? colors.orange : score >= 25 ? colors.yellow : colors.green,
            }]} />
          </View>
          <Text style={s.scoreBarLabel}>{score}/100</Text>
        </View>

        {/* Tabs */}
        <ScrollView horizontal showsHorizontalScrollIndicator={false} style={s.tabBar}>
          {tabs.map((t, i) => (
            <TouchableOpacity key={i} style={[s.tab, tab === i && s.tabActive]} onPress={() => setTab(i)}>
              <Text style={[s.tabText, tab === i && s.tabTextActive]}>{t}</Text>
            </TouchableOpacity>
          ))}
        </ScrollView>

        <View style={s.tabContent}>

          {/* Tab 0 — Transcript */}
          {tab === 0 && (
            <View style={s.transcriptBox}>
              <Text style={s.transcriptText}>{transcript}</Text>
            </View>
          )}

          {/* Tab 1 — Findings */}
          {tab === 1 && (
            findings.length === 0
              ? <View style={s.emptyCard}><Text style={s.emptyText}>✅ No suspicious indicators detected.</Text></View>
              : findings.map(f => (
                <View key={f.key} style={s.findingCard}>
                  <View style={s.findingHeader}>
                    <Text style={s.findingTitle}>{f.icon} {f.label}</Text>
                    <View style={[s.pill, { borderColor: pillColor(f.weight) + '66', backgroundColor: pillColor(f.weight) + '22' }]}>
                      <Text style={[s.pillText, { color: pillColor(f.weight) }]}>{pillLabel(f.weight)}</Text>
                    </View>
                  </View>
                  <Text style={s.findingDesc}>{f.description}</Text>
                  <View style={s.findingMeta}>
                    <Text style={s.findingMetaText}>{f.hits} hit{f.hits > 1 ? 's' : ''}</Text>
                    <Text style={s.findingMetaText}>+{f.contribution} pts</Text>
                  </View>
                </View>
              ))
          )}

          {/* Tab 2 — Action Plan */}
          {tab === 2 && (
            <View>
              {result.score >= 50 && (
                <View style={s.urgentBox}>
                  <Text style={s.urgentTitle}>🚨 IMMEDIATE ACTIONS</Text>
                  {['STOP — Do NOT share any more information.', 'Hang up the call immediately.', 'Call your bank fraud line if details were shared.'].map((a, i) => (
                    <Text key={i} style={s.urgentItem}>• {a}</Text>
                  ))}
                </View>
              )}
              <Text style={s.sectionTitle}>📋 Step-by-Step Plan</Text>
              {(actionSteps || []).map((step, i) => (
                <View key={i} style={s.stepCard}>
                  <Text style={s.stepText}>{step}</Text>
                </View>
              ))}
              {recs.length > 0 && (
                <>
                  <Text style={s.sectionTitle}>🎯 Specific Advice</Text>
                  {recs.map((r, i) => (
                    <View key={i} style={s.recCard}>
                      <Text style={s.recTitle}>{r.icon} {r.title}</Text>
                      <Text style={s.recBody}>{r.body}</Text>
                    </View>
                  ))}
                </>
              )}
            </View>
          )}

          {/* Tab 3 — Helplines */}
          {tab === 3 && (
            <View>
              <Text style={s.sectionTitle}>🚨 Emergency Contacts</Text>
              {EMERGENCY_CONTACTS.map(e => (
                <View key={e.name} style={[s.emergencyCard, { borderColor: e.color + '66' }]}>
                  <Text style={[s.emergencyName, { color: e.color }]}>{e.name}</Text>
                  <Text style={[s.emergencyNum, { color: e.color }]}>{e.number}</Text>
                  <Text style={s.emergencyAvail}>{e.available}</Text>
                </View>
              ))}
              <Text style={[s.sectionTitle, { marginTop: 16 }]}>🏦 Bank Fraud Helplines</Text>
              {BANK_HELPLINES.map(b => (
                <View key={b.bank} style={s.bankCard}>
                  <Text style={s.bankName}>{b.bank}</Text>
                  <Text style={s.bankNum}>{b.number}</Text>
                </View>
              ))}
            </View>
          )}

        </View>
      </ScrollView>
    </View>
  );
}

